/**
 * Build a planetary gearbox through the REAL agent link: a local relay driven
 * as an MCP client over stdio, paired with a headless page on the running dev
 * server (the same harness the agent-*.spec.js files use).
 *
 * Output (all under OUT):
 *   calls.jsonl              every tool call and its structuredContent
 *   Planetary gearbox.waffle.json   the saved document (buildDocumentJson)
 *   capture-<tab>.png        an iso capture of each tab
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync, appendFileSync } from 'node:fs';
import path from 'node:path';
import { McpRelay, pairAgent, relayTestPort } from '/home/claude/workspace/app/tests/gui/helpers/mcp-relay.js';

const require = createRequire('/home/claude/workspace/app/package.json');
const { chromium } = require('playwright-core');

const OUT = process.env.OUT ?? path.dirname(new URL(import.meta.url).pathname) + '/out';
mkdirSync(OUT, { recursive: true });
const LOG = path.join(OUT, 'calls.jsonl');
writeFileSync(LOG, '');

const APP = process.env.APP_URL ?? 'http://localhost:5173';
const AGENT = 'claude-code';
const CALL_TIMEOUT_MS = 900_000;

// ---------------------------------------------------------------- the stage
// Generated by the real generator (waffle_types::gear_planetary, scratch
// planetary_calc): module 1.5 mm, 20°, sun 18 / planet 12 / ring 42, 3
// planets, 50 µm backlash per mesh (25 µm on each gear).
const STAGE = JSON.parse(process.env.STAGE_JSON);
const M = 0.0015;
const W = 0.010; // face width
const SUN = STAGE.gears[0];
const PLANETS = STAGE.gears.slice(1, -1);
const RING = STAGE.gears[STAGE.gears.length - 1];
const RC = STAGE.carrierRadius;
const RIM_R = 0.038;
const SUN_BORE = 0.003;
const PLANET_BORE = 0.0025;
const PIN_R = 0.0024;
const CARRIER_R = 0.028;
const CARRIER_T = 0.004;
const BOSS_R = 0.008;
const BOSS_L = 0.010;
const CARRIER_HOLE = 0.005;

const XY = { origin: [0, 0, 0], normal: [0, 0, 1] };

// ---------------------------------------------------------------- helpers
let relay;
let page;
const t0 = Date.now();

function log(entry) {
	appendFileSync(LOG, JSON.stringify(entry) + '\n');
}

/** One tool call; throws on isError unless `allowError`. */
async function call(tool, args = {}, { allowError = false, label = '' } = {}) {
	const started = Date.now();
	const result = await relay.callTool(tool, args, CALL_TIMEOUT_MS);
	const ms = Date.now() - started;
	const sc = result.structuredContent ?? {};
	log({ t: Date.now() - t0, ms, tool, label, args, isError: !!result.isError, result: sc });
	const brief = result.isError ? `ERROR ${sc.error?.code}: ${sc.error?.message}` : 'ok';
	console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s +${(ms / 1000).toFixed(1)}s] ${tool} ${label} -> ${brief}`);
	if (result.isError && !allowError) {
		throw new Error(`${tool} ${label} failed: ${JSON.stringify(sc.error)}`);
	}
	return sc;
}

const P = (id, x, y) => ({ type: 'Point', id, x, y });
const C = (id, center_id, radius) => ({ type: 'Circle', id, center_id, radius });
const G = (id, params) => ({ type: 'Gear', id, params });

function solidRef(feature_id) {
	return {
		kind: { type: 'Solid' },
		anchor: { type: 'FeatureOutput', feature_id, output_key: { type: 'Main' } },
		selector: { type: 'Role', role: { type: 'EndCapPositive' }, index: 0 },
		policy: { type: 'Strict' }
	};
}

function extrudeParams(sketch_id, depth, { profile_entity_ids = null, combine = 'NewBody', targets = null } = {}) {
	const cut = combine === 'Cut';
	const p = {
		sketch_id,
		profile_index: 0,
		depth,
		direction: null,
		symmetric: false,
		cut,
		merge: false,
		target_body: null,
		depth_mode: { type: 'Blind' },
		combine: { type: combine }
	};
	if (profile_entity_ids) p.profile_entity_ids = profile_entity_ids;
	if (targets) p.targets = targets;
	else if (combine === 'NewBody') p.targets = [];
	return p;
}

async function extrude(label, sketch_id, depth, opts = {}) {
	const r = await call('feature_add', { operation: { type: 'Extrude', params: extrudeParams(sketch_id, depth, opts) } }, { label });
	if (r.warnings?.length) console.log('   warnings:', r.warnings);
	return r;
}

async function rename(feature_id, name) {
	await call('feature_rename', { feature_id, new_name: name }, { label: name });
}

async function nameBody(body_id, name) {
	await call('body_rename', { body_id, new_name: name }, { label: name });
}

async function connector(name, origin, z = [0, 0, 1]) {
	return call(
		'feature_add',
		{ operation: { type: 'MateConnector', params: { name, frame: { origin, z_axis: z, x_axis: [1, 0, 0] } } } },
		{ label: name }
	);
}

/**
 * The extrude direction sign along +z for a sketch on XY: measured on the
 * first body (memory: never assume it).
 */
let DIR = null;
function cutPlane(zStartAlongDir) {
	// A cut tool's sketch plane: `zStartAlongDir` metres before the target's
	// sketch plane, on the side the extrude does NOT go, so the tool spans the
	// target with no coplanar cap.
	return { origin: [0, 0, -DIR * zStartAlongDir], normal: [0, 0, 1] };
}

async function measureDir(body_id) {
	const m = await call('body_measure', { body_id }, { label: 'direction probe' });
	const zmin = m.bbox_min[2], zmax = m.bbox_max[2];
	DIR = Math.abs(zmax) > Math.abs(zmin) ? 1 : -1;
	console.log(`   extrude direction along +z: ${DIR} (z ${zmin.toFixed(4)}..${zmax.toFixed(4)})`);
	return m;
}

/** Bore a body: cylinder tool through it (tool longer than the body, offset start). */
async function bore(label, target_feature_id, cx, cy, r, bodyDepth) {
	const s = await call(
		'sketch_create',
		{ plane: cutPlane(0.002), entities: [P(1, cx, cy), C(2, 1, r)] },
		{ label: `${label} sketch` }
	);
	await rename(s.feature_id, `${label} sketch`);
	const e = await extrude(label, s.feature_id, bodyDepth + 0.004, { combine: 'Cut', targets: [solidRef(target_feature_id)] });
	await rename(e.feature_id, label);
	return e;
}

async function capture(tabName) {
	await call('viewport_view', { view: 'iso', fit: true }, { label: tabName });
	const r = await relay.callTool('viewport_capture', { max_edge_px: 1024 }, CALL_TIMEOUT_MS);
	const img = r.content?.find((c) => c.type === 'image');
	if (img) {
		const file = path.join(OUT, `capture-${tabName.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}.png`);
		writeFileSync(file, Buffer.from(img.data, 'base64'));
		console.log(`   captured ${file}`);
	} else {
		console.log('   capture returned no image:', JSON.stringify(r.structuredContent));
	}
}

// ---------------------------------------------------------------- parts
async function sunPart() {
	const s = await call('sketch_create', { plane: XY, entities: [G(1, SUN)] }, { label: 'sun gear sketch' });
	await rename(s.feature_id, 'Sun gear profile');
	const e = await extrude('sun gear', s.feature_id, W);
	await rename(e.feature_id, 'Sun gear');
	await measureDir(e.bodies_added[0]);
	await bore('Sun bore', e.feature_id, 0, 0, SUN_BORE, W);
	const summary = await call('model_summary');
	await nameBody(summary.bodies[0].body_id, 'Sun gear');
	await connector('Sun axis', [0, 0, 0]);
	return summary;
}

async function planetPart() {
	const planet = { ...PLANETS[0], centerX: 0, centerY: 0, rotationOffset: 0 };
	const s = await call('sketch_create', { plane: XY, entities: [G(1, planet)] }, { label: 'planet gear sketch' });
	await rename(s.feature_id, 'Planet gear profile');
	const e = await extrude('planet gear', s.feature_id, W);
	await rename(e.feature_id, 'Planet gear');
	await bore('Planet bore', e.feature_id, 0, 0, PLANET_BORE, W);
	const summary = await call('model_summary');
	await nameBody(summary.bodies[0].body_id, 'Planet gear');
	await connector('Planet bore axis', [0, 0, 0]);
}

async function ringPart() {
	const rim = await call('sketch_create', { plane: XY, entities: [P(1, 0, 0), C(2, 1, RIM_R)] }, { label: 'rim sketch' });
	await rename(rim.feature_id, 'Ring rim profile');
	const e = await extrude('ring rim', rim.feature_id, W);
	await rename(e.feature_id, 'Ring rim');
	const teeth = await call('sketch_create', { plane: cutPlane(0.002), entities: [G(1, RING)] }, { label: 'ring teeth sketch' });
	await rename(teeth.feature_id, 'Ring teeth profile');
	const cut = await extrude('ring teeth cut', teeth.feature_id, W + 0.004, { combine: 'Cut', targets: [solidRef(e.feature_id)] });
	await rename(cut.feature_id, 'Ring teeth');
	const summary = await call('model_summary');
	await nameBody(summary.bodies[0].body_id, 'Ring gear');
	await connector('Ring axis', [0, 0, 0]);
}

async function carrierPart() {
	const plate = await call('sketch_create', { plane: XY, entities: [P(1, 0, 0), C(2, 1, CARRIER_R)] }, { label: 'carrier plate sketch' });
	await rename(plate.feature_id, 'Carrier plate profile');
	const pe = await extrude('carrier plate', plate.feature_id, CARRIER_T);
	await rename(pe.feature_id, 'Carrier plate');
	// Every boolean consumes its target and re-emits the result as ITS OWN
	// Main output, so the next boolean must target the previous feature, not
	// the plate (run 2: a Strict ref to the consumed plate output silently
	// made a new body).
	let current = pe.feature_id;
	// Pins start INSIDE the plate (no coplanar contact face) and reach through
	// a planet with 1 mm of clearance each side.
	const pinPlane = { origin: [0, 0, DIR * (CARRIER_T / 2)], normal: [0, 0, 1] };
	const centers = STAGE.centers.slice(1);
	for (let k = 0; k < centers.length; k++) {
		const [cx, cy] = centers[k];
		const s = await call('sketch_create', { plane: pinPlane, entities: [P(1, cx, cy), C(2, 1, PIN_R)] }, { label: `pin ${k + 1} sketch` });
		await rename(s.feature_id, `Pin ${k + 1} profile`);
		const e = await extrude(`pin ${k + 1}`, s.feature_id, CARRIER_T / 2 + 0.001 + W + 0.001, { combine: 'Add', targets: [solidRef(current)] });
		await rename(e.feature_id, `Pin ${k + 1}`);
		current = e.feature_id;
	}
	// Output boss on the back, also starting inside the plate.
	const bossPlane = { origin: [0, 0, DIR * (CARRIER_T / 2)], normal: [0, 0, -1] };
	const bs = await call('sketch_create', { plane: bossPlane, entities: [P(1, 0, 0), C(2, 1, BOSS_R)] }, { label: 'boss sketch' });
	await rename(bs.feature_id, 'Output boss profile');
	const be = await extrude('output boss', bs.feature_id, CARRIER_T / 2 + BOSS_L, { combine: 'Add', targets: [solidRef(current)] });
	await rename(be.feature_id, 'Output boss');
	current = be.feature_id;
	// Central clearance hole through plate and boss.
	const hs = await call('sketch_create', { plane: cutPlane(BOSS_L + 0.002), entities: [P(1, 0, 0), C(2, 1, CARRIER_HOLE)] }, { label: 'carrier hole sketch' });
	await rename(hs.feature_id, 'Carrier hole profile');
	const he = await extrude('carrier hole', hs.feature_id, BOSS_L + 0.002 + CARRIER_T + 0.002, { combine: 'Cut', targets: [solidRef(current)] });
	await rename(he.feature_id, 'Carrier hole');
	const summary = await call('model_summary');
	console.log('   carrier bodies:', summary.bodies.map((b) => b.name));
	await nameBody(he.bodies_added[0], 'Carrier');
	await connector('Carrier output', [0, 0, 0], [0, 0, -1]);
}

async function stagePart() {
	// One sketch per gear at its generated position (run 2: a multi-gear
	// sketch's regions were all sub-regions with no addressable loop).
	const gearBody = async (label, params) => {
		const s = await call('sketch_create', { plane: XY, entities: [G(1, params)] }, { label: `${label} sketch` });
		await rename(s.feature_id, `${label} profile`);
		const e = await extrude(label, s.feature_id, W);
		await rename(e.feature_id, label);
		return e;
	};
	const finals = [];
	const sun = await gearBody('Sun', SUN);
	const sunBored = await bore('Sun bore', sun.feature_id, 0, 0, SUN_BORE, W);
	finals.push(['Sun gear', sunBored.bodies_added[0]]);
	for (let k = 0; k < PLANETS.length; k++) {
		const e = await gearBody(`Planet ${k + 1}`, PLANETS[k]);
		const [cx, cy] = STAGE.centers[1 + k];
		const b = await bore(`Planet ${k + 1} bore`, e.feature_id, cx, cy, PLANET_BORE, W);
		finals.push([`Planet ${k + 1}`, b.bodies_added[0]]);
	}
	const rimS = await call('sketch_create', { plane: XY, entities: [P(1, 0, 0), C(2, 1, RIM_R)] }, { label: 'stage rim sketch' });
	await rename(rimS.feature_id, 'Ring rim profile');
	const rim = await extrude('stage rim', rimS.feature_id, W);
	await rename(rim.feature_id, 'Ring rim');
	const teeth = await call('sketch_create', { plane: cutPlane(0.002), entities: [G(1, RING)] }, { label: 'stage ring teeth sketch' });
	await rename(teeth.feature_id, 'Ring teeth profile');
	const cut = await extrude('stage ring teeth cut', teeth.feature_id, W + 0.004, { combine: 'Cut', targets: [solidRef(rim.feature_id)] });
	await rename(cut.feature_id, 'Ring teeth');
	finals.push(['Ring gear', cut.bodies_added[0]]);
	// Carrier plate under the gears with pins up through the planets.
	const plateZ = -DIR * (0.001 + CARRIER_T); // 1 mm below the gears
	const ps = await call('sketch_create', { plane: { origin: [0, 0, plateZ], normal: [0, 0, 1] }, entities: [P(1, 0, 0), C(2, 1, CARRIER_R)] }, { label: 'stage carrier sketch' });
	await rename(ps.feature_id, 'Carrier plate profile');
	const pe = await extrude('stage carrier plate', ps.feature_id, CARRIER_T);
	await rename(pe.feature_id, 'Carrier plate');
	let current = pe.feature_id;
	for (let k = 0; k < PLANETS.length; k++) {
		const [cx, cy] = STAGE.centers[1 + k];
		const pinPlane = { origin: [0, 0, plateZ + DIR * (CARRIER_T / 2)], normal: [0, 0, 1] };
		const s2 = await call('sketch_create', { plane: pinPlane, entities: [P(1, cx, cy), C(2, 1, PIN_R)] }, { label: `stage pin ${k + 1} sketch` });
		await rename(s2.feature_id, `Pin ${k + 1} profile`);
		const e = await extrude(`stage pin ${k + 1}`, s2.feature_id, CARRIER_T / 2 + 0.001 + W + 0.001, { combine: 'Add', targets: [solidRef(current)] });
		await rename(e.feature_id, `Pin ${k + 1}`);
		current = e.feature_id;
	}
	const last = await call('feature_get', { feature_id: current }, { label: 'carrier chain end' });
	const summary = await call('model_summary');
	console.log('   stage bodies:', summary.bodies.map((b) => b.name));
	const carrierBody = summary.bodies.find((b) => b.feature_id === current);
	if (carrierBody) finals.push(['Carrier', carrierBody.body_id]);
	for (const [name, body_id] of finals) await nameBody(body_id, name);
	for (const b of (await call('model_summary')).bodies) {
		const m = await call('body_measure', { body_id: b.body_id }, { label: `measure ${b.name}` });
		console.log(`   ${b.name}: V=${(m.volume_m3 * 1e9).toFixed(1)} mm³ faces=${m.face_count} closed=${m.closed} method=${m.method} methods=${JSON.stringify(m.methods)} exact_unavailable=${JSON.stringify(m.exact_unavailable)}`);
	}
	void last;
	// Top view: the meshing proof.
	await call('viewport_view', { view: 'front', fit: true }, { label: 'stage front (down the Z axis)' });
	const top = await relay.callTool('viewport_capture', { max_edge_px: 2048 }, CALL_TIMEOUT_MS);
	const img = top.content?.find((c) => c.type === 'image');
	if (img) writeFileSync(path.join(OUT, 'capture-stage-axial.png'), Buffer.from(img.data, 'base64'));
	// STEP of the stage, delivered to the agent.
	const step = await relay.callTool('export_step', { deliver: 'agent' }, CALL_TIMEOUT_MS);
	const res = step.content?.find((c) => c.type === 'resource')?.resource;
	if (res?.text) {
		writeFileSync(path.join(OUT, 'planetary-stage.step'), res.text);
		console.log(`   STEP written: ${res.text.length} bytes, warnings=${JSON.stringify(step.structuredContent?.warnings)}`);
	} else {
		console.log('   export_step:', JSON.stringify(step.structuredContent).slice(0, 300));
	}
}

// ---------------------------------------------------------------- main
async function main() {
	const origin = new URL(APP).origin;
	relay = new McpRelay({ port: await relayTestPort(), appUrl: `${origin}/`, allowOrigin: origin });
	await relay.waitListening();
	await relay.initialize(AGENT);
	const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
	const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
	page = await context.newPage();
	page.on('console', (m) => {
		if (m.type() === 'error') console.log('   [page error]', m.text().slice(0, 200));
	});
	try {
		await pairAgent(page, relay, AGENT);
		console.log('paired');
		console.log('status', JSON.stringify(await call('waffle_status')));

		const doc = await call('document_new', { name: 'Planetary gearbox' }, { label: 'new document' });
		const tabs = {};
		tabs.sun = doc.tabs[0].id;
		await call('tab_rename', { tab_id: tabs.sun, name: 'Sun gear' });
		await sunPart();
		await capture('Sun gear');
		await call('document_save', {}, { label: 'after sun' });

		tabs.planet = (await call('tab_add', { kind: 'Part', name: 'Planet gear' })).tab_id;
		await planetPart();
		await capture('Planet gear');
		await call('document_save', {}, { label: 'after planet' });

		tabs.ring = (await call('tab_add', { kind: 'Part', name: 'Ring gear' })).tab_id;
		await ringPart();
		await capture('Ring gear');
		await call('document_save', {}, { label: 'after ring' });

		tabs.carrier = (await call('tab_add', { kind: 'Part', name: 'Carrier' })).tab_id;
		await carrierPart();
		await capture('Carrier');
		await call('document_save', {}, { label: 'after carrier' });

		tabs.stage = (await call('tab_add', { kind: 'Part', name: 'Stage' })).tab_id;
		await stagePart();
		await capture('Stage');
		await call('document_save', {}, { label: 'after stage' });
	} catch (err) {
		console.log('FAILED:', err.message);
		log({ t: Date.now() - t0, failed: err.message });
	} finally {
		try {
			const json = await page.evaluate(() => window.__waffle.buildDocumentJson());
			const file = path.join(OUT, 'Planetary gearbox.waffle.json');
			writeFileSync(file, json);
			console.log(`document written: ${file} (${json.length} bytes)`);
		} catch (err) {
			console.log('could not write the document:', err.message);
		}
		await browser.close();
		console.log('relay exit', await relay.close());
	}
}

main();
