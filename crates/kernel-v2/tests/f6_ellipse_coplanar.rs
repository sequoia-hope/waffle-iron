//! Roadmap F6 (ledger N89 item 4; matrix rows 4.5.5-05, 5.5-03):
//! Stage-0 §4.5.5 coplanar preprocessing on ellipse-bounded planar faces
//! (`refs/text/yang2025_hybrid_boolean.txt:718-732`, Fig. 24(b) `:962-966`).
//!
//! 1. Minimal repro via `KernelV2Adapter` (`make_faces_from_profiles` /
//!    `extrude_face` / `boolean_intersect` / `boolean_union`): an oblique
//!    planar cut of a tilted circular cylinder produces planar caps bounded by
//!    exact `EllipseArc`s; unioning a coplanar solid onto that cap previously
//!    hit Stage 0's `face-unsupported` (`CoplanarFacesUnsupported`) wall.
//! 2. Crossing-rim pin + `BrepArena` structural check: a coplanar partner whose
//!    boundary crosses the elliptical cap rim subdivides `Curve::Ellipse`
//!    chords on the exact ellipse, propagates crossings to the adjacent
//!    cylinder lateral (`rim_overrides`), validates (`validate_solid`), and
//!    retains analytic `Curve::EllipseArc` edges on the output caps.
//! 3. Fig. 24(b)-style sequential union (`:962-966`): 24 elliptical-cap
//!    cylinders with coplanar top (`z = H`) and bottom (`z = 0`) faces
//!    generated by rotating around the perpendicular z-axis in steps of `π/24`
//!    and combined sequentially by `boolean_union`.

use std::collections::HashMap;
use std::f64::consts::PI;

use cad_primitives::{BoolOp, Point2, Point3, Vector3};
use kernel_v2::{
    boolean_op, extrude, tessellate, transform_solid, validate_solid, BrepArena, Curve,
    KernelV2Adapter, Profile, SolidId, Surface,
};
use waffle_types::kernel::{
    Kernel, KernelError, KernelIntrospect, KernelSolidHandle, RenderMesh, RigidPlacement,
};
use waffle_types::ClosedProfile;

fn norm(v: [f64; 3]) -> [f64; 3] {
    let l = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    [v[0] / l, v[1] / l, v[2] / l]
}

fn cross(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

fn plane_x_axis(n: [f64; 3]) -> [f64; 3] {
    let n = norm(n);
    let r = if n[2].abs() < 0.99 {
        [0.0, 0.0, 1.0]
    } else {
        [1.0, 0.0, 0.0]
    };
    norm(cross(r, n))
}

fn rect_profile(x: (f64, f64), y: (f64, f64)) -> (ClosedProfile, HashMap<u32, (f64, f64)>) {
    let mut positions = HashMap::new();
    // Note: in `make_faces_from_profiles` for `n = [0, 0, 1]` and
    // `plane_x_axis = [1, 0, 0]`, `y_axis = n × x = [0, 1, 0]`.
    positions.insert(1, (x.0, y.0));
    positions.insert(2, (x.1, y.0));
    positions.insert(3, (x.1, y.1));
    positions.insert(4, (x.0, y.1));
    let ids = vec![1, 2, 3, 4];
    let profile = ClosedProfile {
        entity_ids: ids.clone(),
        is_outer: true,
        vertex_ids: ids,
        circle: None,
        spline_segments: vec![],
        arc_segments: vec![],
    };
    (profile, positions)
}

fn circle_profile(cx: f64, cy: f64, radius: f64) -> (ClosedProfile, HashMap<u32, (f64, f64)>) {
    let profile = ClosedProfile {
        entity_ids: vec![1],
        is_outer: true,
        vertex_ids: vec![],
        circle: Some(waffle_types::CircleProfile {
            center_u: cx,
            center_v: cy,
            radius,
        }),
        spline_segments: vec![],
        arc_segments: vec![],
    };
    (profile, HashMap::new())
}

fn adapter_box(
    k: &mut KernelV2Adapter,
    x: (f64, f64),
    y: (f64, f64),
    z: (f64, f64),
) -> KernelSolidHandle {
    let n = [0.0, 0.0, 1.0];
    let (prof, pos) = rect_profile(x, y);
    let faces = k
        .make_faces_from_profiles(&[prof], [0.0, 0.0, z.0], n, [1.0, 0.0, 0.0], &pos)
        .expect("stage rectangle face");
    k.extrude_face(faces[0], n, z.1 - z.0).expect("extrude box")
}

/// Build an oblique-cut elliptical-cap cylinder spanning `z ∈ [z0, z1]` via
/// `KernelV2Adapter`: extrude a circular cylinder of `radius` along tilted unit
/// axis `u = [0.6, 0.0, 0.8]` through `pivot`, then intersect with a wide
/// horizontal slab `[z0, z1]`. The horizontal caps at `z = z0` and `z = z1` are
/// exact ellipses with semi-axes `a = radius / 0.8 = 1.25 * radius` and
/// `b = radius`.
fn adapter_elliptical_cap_cylinder(
    k: &mut KernelV2Adapter,
    pivot: [f64; 3],
    radius: f64,
    z0: f64,
    z1: f64,
) -> KernelSolidHandle {
    let u = [0.6, 0.0, 0.8]; // 0.6^2 + 0.8^2 == 1.0 exact
    let s_back = 12.0;
    let origin = [
        pivot[0] - s_back * u[0],
        pivot[1] - s_back * u[1],
        pivot[2] - s_back * u[2],
    ];
    let (cprof, cpos) = circle_profile(0.0, 0.0, radius);
    let cfaces = k
        .make_faces_from_profiles(&[cprof], origin, u, plane_x_axis(u), &cpos)
        .expect("stage tilted circle");
    let tilted_cyl = k
        .extrude_face(cfaces[0], u, 2.0 * s_back)
        .expect("extrude tilted cylinder");
    let slab = adapter_box(k, (-12.0, 12.0), (-12.0, 12.0), (z0, z1));
    k.boolean_intersect(&tilted_cyl, &slab)
        .expect("oblique slab cut produces elliptical-cap cylinder")
}

fn rot_z(theta: f64) -> RigidPlacement {
    let (s, c) = theta.sin_cos();
    RigidPlacement {
        rotation: [[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]],
        translation: [0.0, 0.0, 0.0],
    }
}

fn render_mesh_signed_volume(mesh: &RenderMesh) -> f64 {
    let p = |i: u32| -> [f64; 3] {
        let idx = (i as usize) * 3;
        [
            f64::from(mesh.vertices[idx]),
            f64::from(mesh.vertices[idx + 1]),
            f64::from(mesh.vertices[idx + 2]),
        ]
    };
    let mut six_v = 0.0;
    for t in mesh.indices.chunks_exact(3) {
        let (a, b, c) = (p(t[0]), p(t[1]), p(t[2]));
        six_v += a[0] * (b[1] * c[2] - b[2] * c[1])
            + a[1] * (b[2] * c[0] - b[0] * c[2])
            + a[2] * (b[0] * c[1] - b[1] * c[0]);
    }
    six_v / 6.0
}

/// Exact-bit directed edge balance check on a `waffle_types::kernel::RenderMesh`:
/// every undirected edge must have 2 incident triangles with opposite winding
/// (0 boundary edges, 0 over-used >2 edges). Note that `KernelV2Adapter::tessellate`
/// emits welded/watertight render meshes or per-face triangles; let's check
/// undirected edge multiplicity `<= 2` and `== 2`.
fn check_watertight_render_mesh(mesh: &RenderMesh) -> (usize, usize) {
    let key = |i: u32| -> [u32; 3] {
        let k = (i as usize) * 3;
        [
            mesh.vertices[k].to_bits(),
            mesh.vertices[k + 1].to_bits(),
            mesh.vertices[k + 2].to_bits(),
        ]
    };
    let mut counts: HashMap<([u32; 3], [u32; 3]), usize> = HashMap::new();
    for t in mesh.indices.chunks_exact(3) {
        for (i, j) in [(0usize, 1usize), (1, 2), (2, 0)] {
            let (a, b) = (key(t[i]), key(t[j]));
            let e = if a <= b { (a, b) } else { (b, a) };
            *counts.entry(e).or_insert(0) += 1;
        }
    }
    let open = counts.values().filter(|&&c| c != 2).count();
    let over = counts.values().filter(|&&c| c > 2).count();
    (open, over)
}

#[test]
fn smallest_ellipse_cap_coplanar_repro_via_adapter() {
    let mut k = KernelV2Adapter::new();
    // Oblique-cut cylinder on z ∈ [0, 1] with pivot (0, 0, 0.5), radius 1.0:
    // top cap at z = 1 is an ellipse centered at (0.375, 0, 1) with semi-axes
    // a = 1.25, b = 1.0. Exact volume = π * 1.25 * 1.0 * 1.0 = 1.25 * π.
    let ell_cyl = adapter_elliptical_cap_cylinder(&mut k, [0.0, 0.0, 0.5], 1.0, 0.0, 1.0);
    let m0 = k
        .tessellate(&ell_cyl, 0.01)
        .expect("tessellate oblique cyl");
    let v_cyl = render_mesh_signed_volume(&m0);
    let v_cyl_exact = 1.25 * PI;
    assert!(
        ((v_cyl - v_cyl_exact) / v_cyl_exact).abs() < 2e-3,
        "oblique cyl volume {v_cyl} vs exact {v_cyl_exact}"
    );

    // Flush stacked box on the z = 1.0 ellipse-bounded planar cap whose base
    // crosses the elliptical rim (x ∈ [0.2, 2.0], y ∈ [-0.4, 0.4], z ∈ [1, 2];
    // the ellipse ends at x = 0.375 + 1.25 = 1.625 on y = 0).
    let boss = adapter_box(&mut k, (0.2, 2.0), (-0.4, 0.4), (1.0, 2.0));
    let v_boss = 1.8 * 0.8 * 1.0;

    let out = k
        .boolean_union(&ell_cyl, &boss)
        .unwrap_or_else(|e: KernelError| panic!("coplanar union on ellipse cap failed: {e:?}"));
    let mesh = k.tessellate(&out, 0.01).expect("tessellate union");
    let (_, over) = check_watertight_render_mesh(&mesh);
    assert_eq!(over, 0, "no over-used render edges");
    let v_out = render_mesh_signed_volume(&mesh);
    let v_expect = v_cyl + v_boss;
    assert!(
        ((v_out - v_expect) / v_expect).abs() < 2e-3,
        "flush union volume {v_out} vs sum {v_expect}"
    );
}

/// Run a sequential `boolean_union` of `n_cyl` coplanar-capped elliptical
/// cylinders generated by rotating the seed cylinder around the perpendicular
/// z-axis in steps of `step_rad`, asserting watertightness and matching the
/// 3D render-mesh volume against an independent Cavalieri 2D-slice oracle.
fn assert_rotated_elliptical_cylinder_union_chain(n_cyl: usize, step_rad: f64) {
    let mut k = KernelV2Adapter::new();
    let r_cyl = 2.0;
    let z0 = 0.0;
    let z1 = 0.5;
    let z_pivot = -2.0;
    let seed = adapter_elliptical_cap_cylinder(&mut k, [0.0, 0.0, z_pivot], r_cyl, z0, z1);

    let mut acc = seed.clone();
    for step in 1..n_cyl {
        let theta = (step as f64) * step_rad;
        let rotated = k
            .transform_body(&seed, &rot_z(theta))
            .expect("rotate elliptical cylinder");
        acc = k.boolean_union(&acc, &rotated).unwrap_or_else(|e| {
            panic!(
                "Fig. 24(b) sequential union ({n_cyl} cyls) failed at step {step}/{} \
                 (theta={theta:.4}): {e:?}",
                n_cyl - 1
            )
        });
    }

    let faces = k.list_faces(&acc);
    assert!(
        faces.len() >= n_cyl + 2,
        "expected coplanar caps + lateral patches, got {} faces",
        faces.len()
    );
    let mesh = k
        .tessellate(&acc, 0.01)
        .expect("tessellate rotated elliptical-cylinder union");
    let (_, over) = check_watertight_render_mesh(&mesh);
    assert_eq!(
        over, 0,
        "no over-used render edges in {n_cyl}-cylinder union"
    );

    // Independent Cavalieri slice-area integration oracle over z ∈ [z0, z1]:
    // at height z, cylinder s's cross-section is the ellipse centered at
    // c_s(z) = 0.75 * (z - z_pivot) * (cos θ_s, sin θ_s) with semi-axes
    // a = 2.5 along (cos θ_s, sin θ_s) and b = 2.0 along (-sin θ_s, cos θ_s).
    let a = r_cyl / 0.8;
    let b = r_cyl;
    let thetas: Vec<(f64, f64)> = (0..n_cyl)
        .map(|s| ((s as f64) * step_rad).sin_cos())
        .collect();
    let nz = 16usize;
    let nxy = 400usize;
    let bound = 0.75 * (z1 - z_pivot) + a + 0.1;
    let dx = (2.0 * bound) / (nxy as f64);
    let dz = (z1 - z0) / (nz as f64);
    let mut v_oracle = 0.0;
    for iz in 0..nz {
        let z = z0 + (iz as f64 + 0.5) * dz;
        let offset = 0.75 * (z - z_pivot);
        let mut inside_cells = 0usize;
        for ix in 0..nxy {
            let x = -bound + (ix as f64 + 0.5) * dx;
            for iy in 0..nxy {
                let y = -bound + (iy as f64 + 0.5) * dx;
                let hit = thetas.iter().any(|&(st, ct)| {
                    let xr = x * ct + y * st - offset;
                    let yr = -x * st + y * ct;
                    (xr / a) * (xr / a) + (yr / b) * (yr / b) <= 1.0
                });
                if hit {
                    inside_cells += 1;
                }
            }
        }
        v_oracle += (inside_cells as f64) * dx * dx * dz;
    }

    let v_mesh = render_mesh_signed_volume(&mesh);
    assert!(
        ((v_mesh - v_oracle) / v_oracle).abs() < 5e-3,
        "Fig. 24(b) {n_cyl}-cylinder union volume {v_mesh:.6} vs Cavalieri oracle {v_oracle:.6}"
    );
}

