#!/usr/bin/env node
/**
 * Emit the agent-link tool manifest consumed by the relay
 * (specs/waffle_mcp_server.md §2.4) from app/src/lib/agent/tools/, and the
 * engine-type schemas those tool definitions embed.
 *
 *   node app/scripts/gen-agent-manifest.mjs            # regenerate engineSchemas.generated.js and the relay's bundled manifest
 *   node app/scripts/gen-agent-manifest.mjs --stdout   # print the manifest; exit 1 if engineSchemas.generated.js is stale
 *
 * `engineSchemas.generated.js` holds the definitions of ENGINE_ROOTS and
 * everything they reference, copied from docs/schema/waffle-v5.schema.json.
 * Output is deterministic: keys sorted recursively, 2-space indent, trailing newline.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildManifest, sortKeysDeep } from '../src/lib/agent/tools/manifest.js';

const here = dirname(fileURLToPath(import.meta.url));
const golden = resolve(here, '../../docs/schema/waffle-v5.schema.json');
const engineSchemasFile = resolve(here, '../src/lib/agent/tools/engineSchemas.generated.js');
const toolsIndex = resolve(here, '../src/lib/agent/tools/index.js');
const target = resolve(here, '../../relay/src/waffle_mcp_relay/agent-tools.manifest.json');

/** Engine types tool inputs may refer to (spec §2.4). */
const ENGINE_ROOTS = ['Operation', 'SketchEntity', 'SketchConstraint', 'GeomRef', 'TopoQuery', 'DesignParameter'];

function engineSchemasText() {
	const defs = JSON.parse(readFileSync(golden, 'utf8')).$defs;
	const picked = {};
	const stack = [...ENGINE_ROOTS];
	while (stack.length > 0) {
		const name = stack.pop();
		if (name in picked) continue;
		if (!defs[name]) throw new Error(`${golden} has no $defs/${name}`);
		picked[name] = defs[name];
		for (const m of JSON.stringify(defs[name]).matchAll(/"#\/\$defs\/([A-Za-z0-9_]+)"/g)) stack.push(m[1]);
	}
	return (
		'// GENERATED by app/scripts/gen-agent-manifest.mjs from docs/schema/waffle-v5.schema.json.\n' +
		'// Do not edit: regenerate with `node app/scripts/gen-agent-manifest.mjs`.\n' +
		`export const ENGINE_DEFS = ${JSON.stringify(sortKeysDeep(picked), null, 2)};\n`
	);
}

const toStdout = process.argv.includes('--stdout');
const schemas = engineSchemasText();
let onDisk = null;
try {
	onDisk = readFileSync(engineSchemasFile, 'utf8');
} catch {
	/* first generation */
}
if (onDisk !== schemas) {
	if (toStdout) {
		console.error(`${engineSchemasFile} is stale: run \`node app/scripts/gen-agent-manifest.mjs\``);
		process.exit(1);
	}
	writeFileSync(engineSchemasFile, schemas);
	console.error(`wrote ${engineSchemasFile}`);
}

const { TOOLS } = await import(pathToFileURL(toolsIndex).href);
const manifest = await buildManifest(TOOLS, (text) => createHash('sha256').update(text, 'utf8').digest('hex'));
const text = `${JSON.stringify(sortKeysDeep(manifest), null, 2)}\n`;

if (toStdout) {
	process.stdout.write(text);
} else {
	writeFileSync(target, text);
	console.error(`wrote ${target} (manifest_hash ${manifest.manifest_hash})`);
}
